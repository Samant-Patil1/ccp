const segmenter = new Intl.Segmenter('en', { granularity: 'grapheme' });
const graphemes = (str) => [...segmenter.segment(str)].map((s) => s.segment);

// Filter: drop anything that isn't a visible grapheme cluster (stray
// whitespace, lone variation selectors from copy-paste accidents).
export const EMOJI_CATEGORIES = RAW_CATEGORIES.map((c) => ({
  name: c.name,
  emojis: graphemes(c.chars).filter((e) => e.trim().length > 0),
}));

export function buildEmojiPanel(onPick) {
  const panel = document.createElement('div');
  panel.className = 'emoji-panel-inner';
  for (const cat of EMOJI_CATEGORIES) {
    const label = document.createElement('div');
    label.className = 'emoji-cat';
    label.textContent = cat.name;
    panel.appendChild(label);
    const grid = document.createElement('div');
    grid.className = 'emoji-grid';
    for (const emo of cat.emojis) {
      const btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'emoji-btn-cell';
      btn.textContent = emo;
      btn.addEventListener('click', () => onPick(emo));
      grid.appendChild(btn);
    }
    panel.appendChild(grid);
  }
  return panel;
}
